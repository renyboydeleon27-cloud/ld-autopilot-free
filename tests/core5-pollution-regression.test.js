/* Core 5 atmospheric pollution regression. Run: node tests/core5-pollution-regression.test.js */
'use strict';
const assert = require('node:assert/strict');
const core = require('../ner-core-5.js');
const topic = 'The Great Smog of London — 1952';
const base = { topic, eventYear: 1952, location: 'London, England', facts: [] };
const p1 = core.plan({ ...base, stage: 'P1', narration: 'London, December 1952. Winter tightened its grip, and families fed their coal fires, trying to keep the bitter cold outside.' });
assert.equal(core.validate(p1).ok, true, 'P1 preflight');
assert.match(core.compile(p1), /ACTION DETAIL CONTRACT:/);
assert.match(core.compile(p1), /already-loaded shovel/);
assert.match(core.compile(p1), /Strict true black-and-white grayscale/);
assert.match(core.compile(p1), /One continuous shot/);
const p2 = core.plan({ ...base, stage: 'P2', narration: 'Across the city, household chimneys, factories, and power stations poured smoke into the air. Heating London came with a dangerous cost.' });
assert.equal(core.validate(p2).ok, true, 'P2 preflight');
const p2Prompt = core.compile(p2);
assert.match(p2Prompt, /chimneys visibly releasing coal smoke/);
assert.match(p2Prompt, /raises their gaze toward the smoke/);
assert.doesNotMatch(p2Prompt, /pauses beside a plain gate/);
assert.equal(core.validatePayload(core.payload(p2)).ok, true, 'canonical payload');
assert.equal(core.refine(p2), p2, 'unsupported refinement must not mutate existing P2');
const snapshot = core.stable(p1);
assert.equal(core.refine(p1), p1, 'existing choreography must not mutate P1');
assert.equal(core.stable(p1), snapshot, 'P1 preserved');
const legacy = core.clone(p1);
delete legacy.choreography;
legacy.timing = [{start:0,end:2,phase:'establish'},{start:2,end:6,phase:'action'},{start:6,end:10,phase:'hold'}];
assert.equal(core.validate(legacy).ok, true, 'legacy P1 still valid');
const enriched = core.refine(legacy);
assert.notEqual(enriched, legacy, 'explicit P1 refinement should produce a new spec');
assert.match(core.compile(enriched), /ACTION DETAIL CONTRACT:/);
assert.equal(core.validate(enriched).ok, true);
assert.equal(core.stable(legacy).includes('choreography'), false, 'legacy object not changed');
console.log('Core 5 pollution P1/P2 regression passed');
